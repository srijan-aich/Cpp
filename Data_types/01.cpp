#include<bits/stdc++.h>
using namespace std;

int main() {
//  int, long, long long, short, unsigned int, unsigned long, unsigned long long    
    int x = 10; // 2 bytes 

    long y = 2000; // 4 bytes

    long long z = 3000000; // 8 bytes

    short s = 5; // 2 bytes

    unsigned int u = 20; // 4 bytes

    unsigned long v = 3000000; // 4 bytes

    unsigned long long w = 4000000000; // 8 bytes

    // float, double, long double 
    float a = 3.14; // 4 bytes
    double b = 3.141592653589793; // 8 bytes
    long double c = 3.1415926535897932384626433832795; // 16 bytes
    cout << "value of b = " << b;

    return 0;
} 
 